// ---------- Quiz ----------

export interface AnswerInput {
  choice?: number; // mcq
  bool?: boolean; // true_false
  text?: string; // short_answer, essay
}

export interface GradeFeedback {
  summary: string;
  /** Rubric points: covered / partial / missing, aligned with answer.keyPoints. */
  keyPoints: { status: 'covered' | 'partial' | 'missing'; note: string }[];
  /** What was wrong in the answer and why, with sources. */
  mistakes: { quote: string; why: string; refs: PageRef[] }[];
}

export interface AttemptDTO {
  answer: AnswerInput;
  status: 'grading' | 'graded' | 'failed';
  /** 0..1 */
  score: number | null;
  feedback: GradeFeedback | null;
  error: string | null;
}

export interface QuizItemDTO {
  question: QuestionDTO; // answer included only once attempted
  attempt: AttemptDTO | null;
  /** Spaced-repetition state of this question after the attempt, if it has a card. */
  card: CardState | null;
}

export interface CardState {
  box: number; // 1..5
  dueOn: string; // YYYY-MM-DD
  mastered: boolean;
}

export interface QuizDTO {
  id: number;
  subjectId: number;
  kind: 'practice' | 'review';
  title: string;
  timeLimitSec: number | null;
  startedAt: string;
  finishedAt: string | null;
  items: QuizItemDTO[];
  /** Sum of item scores (0..1 each) / item count, when finished. */
  score: number | null;
}

export interface QuizRequest {
  setId?: number;
  chapterIds?: number[];
  types?: QuestionType[];
  count?: number;
  timeLimitMin?: number | null;
}

