import type { ChapterDTO, ChapterInput, SummaryDTO } from '@zakir/shared';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { fixture, makeTestApp } from '../../test/helpers.ts';
import { validateChapters } from './chapters.ts';

describe('validateChapters', () => {
  const files = [
    { id: 1, name: 'محاضرة 1.pdf', pageCount: 10 },
    { id: 2, name: 'محاضرة 2.pdf', pageCount: 5 },
  ];
  const ch = (title: string, ranges: [number, number, number][], topics: [string, number, number, number][] = []): ChapterInput => ({
    title,
    ranges: ranges.map(([fileId, from, to]) => ({ fileId, from, to })),
    topics: topics.map(([title, fileId, from, to]) => ({ title, fileId, from, to })),
  });

  it('accepts a valid list, including a chapter spanning two files', () => {
    expect(validateChapters([ch('أ', [[1, 1, 6]]), ch('ب', [[1, 7, 10], [2, 1, 5]], [['موضوع', 2, 2, 3]])], files)).toEqual([]);
  });

  it('reports overlaps, bad ranges, unknown files, topics outside the chapter, empty titles', () => {
    const p = validateChapters(
      [ch('أ', [[1, 1, 6]]), ch('ب', [[1, 5, 12]]), ch('', [[3, 1, 2]]), ch('د', [[2, 1, 2]], [['خارج', 2, 4, 5]]), ch('هـ', [])],
      files,
    );
    expect(p.join('\n')).toMatch(/فيه 10 صفحة فقط/);
    expect(p.join('\n')).toMatch(/ليس من ملفات المحتوى/);
    expect(p.join('\n')).toMatch(/خارج نطاق الشابتر/);
    expect(p.join('\n')).toMatch(/العنوان مطلوب/);
    expect(p.join('\n')).toMatch(/يحتاج نطاق صفحات/);
    // Names are wrapped in bidi isolates (U+2068…U+2069) for correct display of mixed-direction titles.
    expect(validateChapters([ch('أ', [[1, 1, 6]]), ch('ب', [[1, 5, 8]])], files)[0]).toMatch(/متداخلة مع «⁨أ⁩»/);
  });
});

describe('chapters, segmentation and summaries', () => {
  let t: ReturnType<typeof makeTestApp>;
  let subjectId: number;
  let fileId: number;

  beforeEach(async () => {
    t = makeTestApp();
    subjectId = (await t.json('POST', '/api/subjects', { name: 'أحياء' })).body.id;
    fileId = (await t.upload(subjectId, 'content', [{ name: 'محاضرة 1.pdf', data: fixture('text.pdf') }]))[0]!.fileId;
    // Same PDF with a trailing comment, so it is a different file (not a duplicate).
    const exam = await t.upload(subjectId, 'past_exam', [{ name: 'اختبار 2024.pdf', data: Buffer.concat([fixture('text.pdf'), Buffer.from('\n%exam\n')]) }]);
    expect(exam[0]!.ok).toBe(true);
    await t.settle();
    expect((await t.json('GET', `/api/subjects/${subjectId}/files`)).body).toHaveLength(2);
  });
  afterEach(() => t.cleanup());

  const goodSegment = () => ({
    chapters: [
      { title: 'الخلية', ranges: [{ file: `F${fileId}`, from: 1, to: 2 }], topics: [{ title: 'الميتوكوندريا', file: `F${fileId}`, from: 2, to: 2 }] },
      { title: 'الرايبوسومات', ranges: [{ file: `F${fileId}`, from: 3, to: 3 }], topics: [] },
    ],
  });

  async function segment() {
    t.provider.script.segment = [goodSegment];
    const job = await t.json('POST', `/api/subjects/${subjectId}/chapters/auto`);
    expect(job.status).toBe(200);
    await t.settle();
    return (await t.json<{ chapters: ChapterDTO[] }>('GET', `/api/subjects/${subjectId}/chapters`)).body.chapters;
  }

  it('auto-segments content files only, from a page outline', async () => {
    const chapters = await segment();
    const { req } = t.provider.calls.find((c) => c.kind === 'segment')!;
    expect(req.tools).toBe('none');
    expect(req.user).toContain(`=== F${fileId} — «محاضرة 1.pdf» — 3 صفحة`);
    expect(req.user).toContain('p1: الفصل الأول: الخلية');
    expect(req.user).not.toContain('اختبار 2024'); // past exams are not chapters
    expect(chapters.map((c) => [c.title, c.pageCount, c.autoGenerated, c.summary])).toEqual([
      ['الخلية', 2, true, 'none'],
      ['الرايبوسومات', 1, true, 'none'],
    ]);
    expect(chapters[0]!.topics).toEqual([{ title: 'الميتوكوندريا', fileId, from: 2, to: 2 }]);
  });

  it('sends uncovered pages back to the model and retries once', async () => {
    const gap = () => ({ chapters: [{ title: 'الخلية', ranges: [{ file: `F${fileId}`, from: 1, to: 2 }], topics: [] }] });
    t.provider.script.segment = [gap, goodSegment];
    await t.json('POST', `/api/subjects/${subjectId}/chapters/auto`);
    await t.settle();
    const calls = t.provider.calls.filter((c) => c.kind === 'segment');
    expect(calls).toHaveLength(2);
    expect(calls[1]!.req.user).toContain('غير مغطاة بأي شابتر: 3');
    expect((await t.json('GET', `/api/subjects/${subjectId}/chapters`)).body.chapters).toHaveLength(2);
  });

  it('summarizes a chapter with its full page text, converts refs, and detects outdated summaries', async () => {
    const [ch1] = await segment();
    t.provider.script.summarize = [
      () => ({
        quick: [
          { text: 'الخلية (Cell) هي الوحدة الأساسية للحياة.', refs: [{ file: `F${fileId}`, page: 1 }] },
          { text: 'Mitochondria (الميتوكوندريا) مكان التنفس الخلوي.', refs: [{ file: `F${fileId}`, page: 2 }] },
          { text: 'تنتج الميتوكوندريا ATP.', refs: [{ file: `F${fileId}`, page: 2 }] },
        ],
        detailed: [{ heading: 'الخلية', points: [{ text: 'غشاء بلازمي يتحكم في المواد.', refs: [{ file: `F${fileId}`, page: 1 }] }] }],
      }),
    ];
    await t.json('POST', `/api/chapters/${ch1!.id}/summarize`);
    await t.settle();

    const { req } = t.provider.calls.find((c) => c.kind === 'summarize')!;
    expect(req.user).toContain(`[F${fileId}:p1]`);
    expect(req.user).toContain(`[F${fileId}:p2]`);
    expect(req.user).not.toContain(`[F${fileId}:p3]`); // other chapter's page
    expect(req.user).toContain('وتنتج معظم طاقة الخلية على شكل ATP.'); // full text, not the outline

    let got = (await t.json<{ chapter: ChapterDTO; summary: SummaryDTO }>('GET', `/api/chapters/${ch1!.id}`)).body;
    expect(got.chapter.summary).toBe('ready');
    expect(got.summary.quick[1]).toEqual({ text: 'Mitochondria (الميتوكوندريا) مكان التنفس الخلوي.', refs: [{ fileId, page: 2 }] });
    expect(got.summary.stale).toBe(false);

    // Page text changes (e.g. a page re-read) → summary is outdated.
    t.db.prepare(`UPDATE pages SET text = text || ' تعديل' WHERE file_id = ? AND page_no = 1`).run(fileId);
    got = (await t.json('GET', `/api/chapters/${ch1!.id}`)).body;
    expect(got.chapter.summary).toBe('stale');
    expect(got.summary.stale).toBe(true);
  });

  it('rejects a summary citing a page outside the chapter, after one retry', async () => {
    const [ch1] = await segment();
    const bad = () => ({
      quick: [1, 2, 3].map(() => ({ text: 'نقطة', refs: [{ file: `F${fileId}`, page: 3 }] })),
      detailed: [{ heading: 'ق', points: [{ text: 'نقطة', refs: [] }] }],
    });
    t.provider.script.summarize = [bad, bad];
    const job = (await t.json('POST', `/api/chapters/${ch1!.id}/summarize`)).body;
    await t.settle();
    const done = (await t.json('GET', `/api/jobs/${job.id}`)).body;
    expect(done.status).toBe('failed');
    expect(done.errorCode).toBe('INVALID_OUTPUT');
    const second = t.provider.calls.filter((c) => c.kind === 'summarize')[1]!.req.user;
    expect(second).toContain(`المرجع F${fileId}:p3 غير موجود في صفحات الشابتر`);
    expect(second).toContain('بلا مرجع');
    expect((await t.json('GET', `/api/chapters/${ch1!.id}`)).body.summary).toBeNull();
  });

  it('manual edits keep chapter ids, delete omitted chapters, and validate in Arabic', async () => {
    const [ch1, ch2] = await segment();
    const res = await t.json('PUT', `/api/subjects/${subjectId}/chapters`, {
      chapters: [{ id: ch1!.id, title: 'الخلية والعضيات', ranges: [{ fileId, from: 1, to: 3 }], topics: [] }],
    });
    expect(res.status).toBe(200);
    expect(res.body.chapters.map((c: ChapterDTO) => [c.id, c.title, c.pageCount, c.autoGenerated])).toEqual([[ch1!.id, 'الخلية والعضيات', 3, true]]);
    expect((await t.json('GET', `/api/chapters/${ch2!.id}`)).status).toBe(404);

    const bad = await t.json('PUT', `/api/subjects/${subjectId}/chapters`, {
      chapters: [
        { title: 'أ', ranges: [{ fileId, from: 1, to: 2 }], topics: [] },
        { title: 'ب', ranges: [{ fileId, from: 2, to: 3 }], topics: [] },
      ],
    });
    expect(bad.status).toBe(400);
    expect(bad.body.error).toContain('متداخلة');
  });

  it('sets exam scope to chapters of the same subject only', async () => {
    const [ch1, ch2] = await segment();
    const s = (await t.json('POST', `/api/subjects/${subjectId}/exams`, { title: 'الفصلي' })).body;
    const examId = s.exams[0].id;
    expect((await t.json('PUT', `/api/exams/${examId}/scope`, { chapterIds: [ch2!.id, ch1!.id] })).status).toBe(200);
    expect((await t.json('GET', `/api/subjects/${subjectId}`)).body.exams[0].chapterIds.sort()).toEqual([ch1!.id, ch2!.id].sort());
    expect((await t.json('PUT', `/api/exams/${examId}/scope`, { chapterIds: [999] })).status).toBe(400);
  });

  it('refuses to segment a subject without content files', async () => {
    const other = (await t.json('POST', '/api/subjects', { name: 'فارغة' })).body.id;
    const r = await t.json('POST', `/api/subjects/${other}/chapters/auto`);
    expect(r.status).toBe(400);
    expect(r.body.error).toContain('ارفع ملفات محتوى');
  });
});
